result={'status':'RUNNING','cases':[]};started=False;c=None;adapter=None;initialized=False
try:
 remote("import unreal,builtins; assert unreal.EditorLevelLibrary.get_game_world() is None; w=unreal.EditorLevelLibrary.get_editor_world(); builtins.parking_check_mode=w.get_world_settings().get_editor_property('DefaultGameMode'); s=unreal.get_default_object(unreal.load_class(None,'/Script/UnrealEd.EditorPerformanceSettings')); builtins.parking_check_throttle=s.get_editor_property('bThrottleCPUWhenNotForeground'); s.set_editor_property('bThrottleCPUWhenNotForeground',False); w.get_world_settings().set_editor_property('DefaultGameMode',unreal.load_class(None,'/Script/AirSim.AirSimGameMode')); unreal.EditorLevelLibrary.editor_play_simulate()")
 started=True
 for _ in range(40):
  try:
   c=airsim.CarClient(timeout_value=3);names=c.listVehicles()
   if len(names)==24:break
  except Exception:pass
  time.sleep(.5)
 for v in names:c.enableApiControl(True,vehicle_name=v);c.setCarControls(airsim.CarControls(brake=1),vehicle_name=v)
 time.sleep(.5)
 scene=ue_script(c,'export_scene.py',ROOT/'runs/ue_scene/scene.json');origin=tuple(v/100 for v in scene['world_origin_cm']);home=c.simGetVehiclePose(vehicle_name='Car_0_0');world=absolute_ue(c,'Car_0_0',origin)[0]
 def fixture(action):
  p=ROOT/'runs/ue_node_pairs';p.mkdir(exist_ok=True);(p/'fleet_request.json').write_text(json.dumps(dict(action=action,vehicles=names if action in ['INIT','RESTORE','FREEZE'] else ['Car_0_0'],time_scale=1,physics_substepping=True)))
  ue_script(c,'node_pair_fleet_fixture.py',p/'fleet_status.json')
 fixture('INIT');initialized=True
 m=TransportMap(ROOT/'config/topology/industrialarea_ue_internal_waiting_transport.json');n=json.load(open(ROOT/'config/topology/industrialarea_ue_internal_waiting_network.json'))
 selected=([next(p for p in before['parking'] if p['node']==node) for node in args.nodes]
           if args.nodes else sorted(before['parking'],key=lambda a:abs(a['heading_error_deg']),reverse=True))
 for item in selected:
  q=item['node'];edge=next(e for e in n['edges'] if e['to_node']==q and e['kind']=='service_access');ks=sorted([k for k in m.edges if k.startswith(edge['edge_id']+'__test')],key=lambda k:int(k.rsplit('test',1)[1]));p=RouteGeometry(m,ks,[],edge['from_node'],[q]);p.arrival_heading=math.radians(n['service_nodes'][q]['heading_deg']);s=max(0,p.length-12);x,y=p.point(s);h=p.heading(s);target=[x+1.16425*math.cos(h),y+1.16425*math.sin(h),.894]
  fixture('FREEZE');c.simPause(True);fixture('ACTIVATE');hp=home.position;c.simSetVehiclePose(airsim.Pose(airsim.Vector3r(hp.x_val+target[0]-world[0],hp.y_val+target[1]-world[1],hp.z_val-target[2]+world[2]),airsim.to_quaternion(0,0,h)),True,vehicle_name='Car_0_0');c.setCarControls(airsim.CarControls(brake=1),vehicle_name='Car_0_0');c.simPause(False);time.sleep(.4)
  c.simRunConsoleCommand("py import builtins,runpy; builtins.fleet_monitor_request={'vehicles':['Car_0_0'],'file':'parking_check_live.json'}; runpy.run_path("+repr(str(ROOT/'scripts/ue/monitor_fleet.py'))+")")
  time.sleep(.2);observer=FleetFileObserver(ROOT/'runs/ue_scene/parking_check_live.json')
  cfg=json.load(open(ROOT/'config/runtime/industrialarea_ue_interwarehouse_1v_1cycles.json'))['adapter'];cfg.update(vehicle_ids=('Car_0_0',),origin_ue_m=origin,command_ttl_s=2,state_timeout_s=5,speed_rise_m_s2=.6,speed_error_gain=.6)
  adapter=AirSimAdapter(AirSimConfig(**cfg),OUT/('native_'+q+'.jsonl'),watchdog=False);adapter.open();adapter.snapshot_provider=observer.snapshot;adapter.last_source={};adapter.source_advanced={};begin=time.monotonic();peak=0;seq=1;case=dict(node=q,status='RUNNING',samples=[]);result['cases'].append(case)
  while time.monotonic()-begin<60:
   state=rear(adapter.read_states()['Car_0_0']);audit,errors=observer.read('Car_0_0')
   if errors:raise RuntimeError(q+' '+str(errors))
   error,pr=p.project((state.x,state.y),s,ahead=3);s=max(s,pr);peak=max(peak,error);remaining=p.length-s;now=time.monotonic()-begin
   case['samples'].append([now,state.x,state.y,state.heading,state.speed,s])
   if error>.7:raise RuntimeError(q+' path error '+str(error))
   if remaining<.22 and stopped_at_point(state,p.point(p.length),p.arrival_heading):break
   target=min(1.2,p.speed_cap(s),remaining*.8,math.sqrt(1.2*max(0,remaining)));target=-target if p.reverse(s) else target;delta=p.steering((state.x,state.y),state.heading,s,speed=state.speed);omega=target*math.tan(delta)/2.3285 if abs(target)>.05 else 0
   adapter.send(ControlCommand('Car_0_0',seq,adapter.clock(),target,omega,ttl=2));seq+=1;time.sleep(.04)
  else:raise RuntimeError(q+' terminal timeout '+str(case['samples'][-1]))
  adapter.close();adapter=None;time.sleep(.25);observer.snapshot();state=rear(VehicleState('Car_0_0',**{k:observer.latest['states']['Car_0_0'][k] for k in ['x','y','heading','speed']}))
  case.update(status='PASS',maximum_path_error_m=peak,position_error_m=math.dist((state.x,state.y),p.point(p.length)),heading_error_deg=math.degrees((state.heading-p.arrival_heading+math.pi)%(2*math.pi)-math.pi),elapsed_s=now)
  (OUT/'native_parking.json').write_text(json.dumps(result,indent=2));print(q,'PASS',case['heading_error_deg'],case['position_error_m'],flush=True)
 result['status']='PASS'
except Exception as e:
 result.update(status='FAIL',failure=repr(e))
 if 'case' in locals() and case['status']=='RUNNING':case.update(status='FAIL',failure=repr(e))
 traceback.print_exc()
finally:
 if adapter:
  try:adapter.close()
  except Exception:pass
 if c and initialized:
  try:fixture('FREEZE');fixture('RESTORE')
  except Exception as e:result['restore_error']=repr(e)
 if started:
  try:
   remote('import unreal; unreal.EditorLevelLibrary.editor_end_play()');time.sleep(1);remote("import unreal,builtins; unreal.EditorLevelLibrary.get_editor_world().get_world_settings().set_editor_property('DefaultGameMode',builtins.parking_check_mode); unreal.get_default_object(unreal.load_class(None,'/Script/UnrealEd.EditorPerformanceSettings')).set_editor_property('bThrottleCPUWhenNotForeground',builtins.parking_check_throttle)");result['editor_restored']=True
  except Exception as e:result['editor_restore_error']=repr(e)
 (OUT/'native_parking.json').write_text(json.dumps(result,indent=2));print(result['status'],result.get('failure'),flush=True)

if result['status']!='PASS' or not result.get('editor_restored'):raise SystemExit(1)
